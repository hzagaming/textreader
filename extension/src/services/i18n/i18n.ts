const dictionaries: Record<SupportedLanguage, Record<MessageKey, string>> = {
  en,
  zh,
  ja,
  ko,
}

function currentBrowserLanguage(): string {
  if (typeof chrome !== 'undefined' && chrome.i18n?.getUILanguage)
    return chrome.i18n.getUILanguage()
  return typeof navigator === 'undefined' ? 'en' : navigator.language
}

export function resolveUiLanguage(
  preference: UiLanguage,
  browserLanguage = currentBrowserLanguage(),
): SupportedLanguage {
  return preference === 'auto'
    ? (normalizeSupportedLanguage(browserLanguage) ?? 'en')
    : preference
}

export function createTranslator(
  preference: UiLanguage,
  browserLanguage?: string,
): Translator {
  const dictionary = dictionaries[resolveUiLanguage(preference, browserLanguage)]
  return (key, substitutions = []) => {
    let message = dictionary[key] ?? en[key]
    substitutions.forEach((value, index) => {
      message = message.replaceAll(`{${index}}`, value)
    })
    return message
  }
}

export function translateErrorCode(code: string | undefined, t: Translator): string {
  const keys: Record<TextReaderErrorCode, MessageKey> = {
    NO_SELECTION: 'noSelection',
    EMPTY_TEXT: 'emptyText',
    TTS_ERROR: 'ttsError',
    UNSUPPORTED_PAGE: 'unavailableOnPage',
    PERMISSION_ERROR: 'permissionError',
    UNKNOWN: 'unknownError',
  }
  const key =
    code && Object.hasOwn(keys, code) ? keys[code as TextReaderErrorCode] : 'unknownError'
  return t(key)
}
